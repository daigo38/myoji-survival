#!/usr/bin/env python3
"""Regenerate public/surnames.js from the 名字由来net national surname ranking.

Takes the top 1000 surnames with their approximate populations and scales each
by SCALE, rounding to the nearest integer (e.g. 佐藤 1,798,000 -> 180).
"""
import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

URL = "https://myoji-yurai.net/prefectureRanking.htm"
PAGES = [{}, {"prefecture": "全国", "page": "1"}]  # ranks 1-500, 501-1000
TOP = 1000
SCALE = 0.0001
OUT = Path(__file__).resolve().parent.parent / "public" / "surnames.js"

ROW = re.compile(
    r'<td style="text-align:center;">(\d+)位</td>\s*'
    r'<td[^>]*><a href="searchResult\.htm\?myojiKanji=[^"]*">([^<]+)</a></td>\s*'
    r'<td[^>]*>およそ([\d,]+)人</td>'
)


def fetch(params):
    url = URL + ("?" + urllib.parse.urlencode(params) if params else "")
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read().decode("utf-8")


def main():
    ranks = {}
    for params in PAGES:
        for rank, name, people in ROW.findall(fetch(params)):
            ranks[int(rank)] = (name, int(people.replace(",", "")))
    rows = [ranks[r] for r in sorted(ranks)[:TOP]]
    if len(rows) != TOP:
        raise SystemExit(f"expected {TOP} surnames, got {len(rows)}")

    lines = ",\n".join(
        f"  [{json.dumps(name, ensure_ascii=False)}, {round(people * SCALE)}]" for name, people in rows
    )
    OUT.write_text(
        "// Generated by scripts/fetch_surnames.py. Do not edit by hand.\n"
        "// 名字由来net 全国名字ランキング上位1000位の「およその人数」× 0.0001（四捨五入）。\n"
        f"const SURNAMES = [\n{lines}\n];\n",
        encoding="utf-8",
    )
    total = sum(round(p * SCALE) for _, p in rows)
    print(f"wrote {OUT.name}: {len(rows)} surnames, {total} people")


if __name__ == "__main__":
    main()
